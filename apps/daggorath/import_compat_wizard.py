#!/usr/bin/env python3
"""Import the bounded C3 Wizard vector closure and deterministic frame oracles."""
from pathlib import Path
import argparse,hashlib,json,re,subprocess

REFERENCE=Path('/Volumes/SEDONA/Projects/daggorath-reference')
COMMIT='a94326f00ebb16a106b540c58bc2ccf5f7b66dac'
APP=Path(__file__).resolve().parent

def packed(section): return bytes(int(v,2) for v in re.findall(r'^\s*FCB\s+%([01]{8})',section,re.M))
def five(data,bit):
    value=0
    for _ in range(5): value=(value<<1)|((data[bit//8]>>(7-bit%8))&1);bit+=1
    return value
def expand(data): return bytes(five(data,5+i*5) for i in range(five(data,0)+1))
def trunc_div(a,b): return abs(a)//b*(-1 if a<0 else 1)
def line(frame,p,fade):
    x0,y0,x1,y1=p;dx=x1-x0;dy=y1-y0;n=max(abs(dx),abs(dy))
    if not n or fade==255:return
    xx=x0*256+128;yy=y0*256+128;sx=trunc_div(dx*256,n);sy=trunc_div(dy*256,n)
    count=fade+1
    for _ in range(n):
        count-=1
        if count==0:
            count=fade+1;x=xx>>8;y=yy>>8
            if 0<=x<256 and 0<=y<192:frame[y*32+x//8]|=128>>(x&7)
        xx+=sx;yy+=sy
def glyphs():
    sw=(REFERENCE/'SWCHAR.ASM').read_text();normal=packed(sw[sw.index('SWCTAB  EQU'):sw.index('SPCTAB')])
    return [bytes(five(normal[c*5:(c+1)*5],5+r*5)<<2 for r in range(7)) for c in range(31)]
def cell(frame,g,at,code,inverse=0):
    row,col=divmod(at,32);base=row*256+col
    for y,v in enumerate(g[code]):frame[base+y*32]=v^inverse
def parse_segments():
    d4=(REFERENCE/'D4.ASM').read_text();segments=[];locations=[]
    for label,end in (('WIZ1','WIZ2'),('WIZ0','VIPER')):
        start=re.search(r'^'+label+r'\s',d4,re.M).start();chunk=d4[start:]
        chunk=chunk[:re.search(r'^'+end+r'\s',chunk,re.M).start()]
        point=None
        for offset,line_text in enumerate(chunk.splitlines()):
            clean=line_text.split(';')[0];m=re.search(r'\b(SVORG|SVECT|FCB|SVNEW|SVEND)\s*(.*)',clean)
            if not m:continue
            op,arg=m.groups();arg=arg.strip()
            if op in ('SVNEW','SVEND') or arg=='V$NEW':point=None;continue
            if op=='FCB' and not re.fullmatch(r'\d+,\s*\d+',arg):continue
            y,x=map(int,arg.split(','))
            if op=='SVORG':point=(x,y);continue
            if point:segments.append((*point,x,y));locations.append({'label':label,'line':d4[:start].count('\n')+offset+1})
            point=(x,y)
    return segments,locations
def main():
    ap=argparse.ArgumentParser();ap.add_argument('--out',type=Path,default=APP);args=ap.parse_args();out=args.out.resolve()
    assert subprocess.check_output(['git','-C',str(REFERENCE),'rev-parse','HEAD'],text=True).strip()==COMMIT
    segs,locations=parse_segments();assert len(segs)==84
    asm=['* Generated by import_compat_wizard.py from D4.ASM at '+COMMIT,
         'WIZARD_SEGMENT_COUNT equ '+str(len(segs)),'wizard_segments']
    asm += ['        fcb     '+','.join(f'${v:02x}' for v in s) for s in segs]
    target=out/'src/compat/wizard-data.asm';target.parent.mkdir(parents=True,exist_ok=True);target.write_text('\n'.join(asm)+'\n')
    once=(REFERENCE/'ONCE.ASM').read_text();status=expand(packed(once[once.index(';  Display COPYRIGHT'):once.index('DEMO10  DEC')]))
    part=once[once.index('DEMO10  DEC'):once.index(';  Create Autoplay')]
    intro1=expand(packed(part[:part.index(';welcome message (part II)')]))
    intro2=expand(packed(part[part.index(';welcome message (part II)'):]))
    header='/* Generated from ONCE.ASM at '+COMMIT+'. */\nstatic const unsigned char compat_status[]={'+','.join(map(str,status))+'};\nstatic const unsigned char compat_opening_intro1[]={'+','.join(map(str,intro1))+'};\nstatic const unsigned char compat_opening_intro2[]={'+','.join(map(str,intro2))+'};\nstatic const unsigned char compat_prepare[]={16,18,5,16,1,18,5,27};\n'
    (out/'src/compat/opening-data.h').write_text(header)
    g=glyphs();fixture=out/'test/fixtures/compat-c3';fixture.mkdir(parents=True,exist_ok=True);records=[]
    def make(name,fade=None,welcome=False,prepare=False):
        f=bytearray(6144);f[152*32:160*32]=b'\xff'*(8*32)
        for i,c in enumerate(status):cell(f,g,19*32+i,c,255)
        if fade is not None:
            for p in segs:line(f,p,fade)
        if welcome:
            cur=0
            for c in intro1+intro2:
                if c==31:cur=(cur+32)&~31
                elif c<31:cell(f,g,20*32+cur,c);cur+=1
        if prepare:
            for i,c in enumerate((16,18,5,16,1,18,5,27)):cell(f,g,9*32+12+i,c)
        data=bytes(f);(fixture/(name+'.frame')).write_bytes(data);records.append({'name':name,'sha256':hashlib.sha256(data).hexdigest()})
    make('00-first-strokes',32);make('01-emerging',16);make('02-complete',0);make('03-welcome',0,True);make('04-fade',14);make('05-near-black');make('06-prepare',prepare=True)
    manifest={'referenceCommit':COMMIT,'segmentCount':len(segs),'locations':locations,'status':list(status),'frames':records}
    (fixture/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
if __name__=='__main__':main()

#!/usr/bin/env python3
"""Generate the immutable C2 glyph table and logical-frame oracles.

The source repository is read only and pinned to the same recovered revision as
the existing Daggorath provenance. Generated outputs are repository inputs, so
normal builds do not depend on the external checkout.
"""
from pathlib import Path
import argparse,hashlib,json,re,subprocess

REFERENCE=Path('/Volumes/SEDONA/Projects/daggorath-reference')
COMMIT='a94326f00ebb16a106b540c58bc2ccf5f7b66dac'
APP=Path(__file__).resolve().parent

def packed(section):
    return bytes(int(v,2) for v in re.findall(r'^\s*FCB\s+%([01]{8})',section,re.M))

def five(data,bit):
    value=0
    for _ in range(5):
        value=(value<<1)|((data[bit//8]>>(7-bit%8))&1);bit+=1
    return value

def normal_glyph(data,code):
    source=data[code*5:(code+1)*5]
    assert five(source,0)==6
    return bytes(five(source,5+row*5)<<2 for row in range(7))

def expand_string(data):
    count=five(data,0)+1
    return bytes(five(data,5+i*5) for i in range(count))

class Text:
    def __init__(self,glyphs): self.frame=bytearray(6144);self.cursor=0;self.glyphs=glyphs
    def clear(self): self.frame[160*32:192*32]=bytes(32*32);self.cursor=0
    def put(self,code):
        if code==0x24: self.cursor=127 if self.cursor==0 else self.cursor-1;return
        if code==0x1f: self.cursor=(self.cursor+32)&~31
        elif code<0x24:
            row,col=divmod(self.cursor,32);base=(160+row*8)*32+col
            for y,value in enumerate(self.glyphs[code]):self.frame[base+y*32]=value
            self.cursor+=1
        if self.cursor>=128:
            self.frame[160*32:184*32]=self.frame[168*32:192*32]
            self.frame[184*32:192*32]=bytes(8*32);self.cursor=96

def main():
    parser=argparse.ArgumentParser();parser.add_argument('--out',type=Path,default=APP)
    args=parser.parse_args();out=args.out.resolve()
    commit=subprocess.check_output(['git','-C',str(REFERENCE),'rev-parse','HEAD'],text=True).strip()
    assert commit==COMMIT
    sw=(REFERENCE/'SWCHAR.ASM').read_text()
    normal=packed(sw[sw.index('SWCTAB  EQU'):sw.index('SPCTAB')]);assert len(normal)==155
    special=packed(sw[sw.index('SPCTAB  EQU'):]);assert len(special)>=28
    glyphs=[normal_glyph(normal,c) for c in range(31)]
    glyphs.extend(special[i:i+7] for i in range(0,28,7));assert len(glyphs)==35
    asm=['* Generated by import_compat_text.py from SWCHAR.ASM at '+COMMIT,
         'compat_glyphs']
    asm += ['        fcb     '+','.join(f'${v:02x}' for v in glyph) for glyph in glyphs]
    asm.append('')
    target=out/'src/compat/text-glyphs.asm';target.parent.mkdir(parents=True,exist_ok=True)
    target.write_text('\n'.join(asm))

    header=['/* Generated by import_compat_text.py from recovered source '+COMMIT+'. */',
      'static const unsigned char compat_packed_font[]={'+','.join(map(str,normal))+'};']

    once=(REFERENCE/'ONCE.ASM').read_text();intro=once[once.index('DEMO10  DEC'):once.index(';  Create Autoplay')]
    blobs=[packed(intro[:intro.index(';welcome message (part II)')]),packed(intro[intro.index(';welcome message (part II)'):])]
    intro1,intro2=map(expand_string,blobs)
    header += ['static const unsigned char compat_intro1[]={'+','.join(map(str,intro1))+'};',
      'static const unsigned char compat_intro2[]={'+','.join(map(str,intro2))+'};']
    (out/'test').mkdir(parents=True,exist_ok=True)
    (out/'test/compat-c2-data.h').write_text('\n'.join(header)+'\n')
    fixture=out/'test/fixtures/compat-c2';fixture.mkdir(parents=True,exist_ok=True)
    text=Text(glyphs);records=[]
    def save(name):
        data=bytes(text.frame);(fixture/(name+'.frame')).write_bytes(data)
        records.append({'name':name,'cursor':text.cursor,'sha256':hashlib.sha256(data).hexdigest()})
    text.clear();save('00-blank')
    text.put(0x1f);text.put(0x1e);save('01-lone-dot')
    text.put(0x1c);text.put(0x24);save('01b-dot-cursor')
    # HUMAN.ASM:HMAN30 erases the old cursor by emitting display code zero.
    # The blank glyph advances the cursor exactly like any printable code.
    text.put(0);save('01c-erased-cursor')
    text.clear()
    for code in intro1[:9]:text.put(code)
    save('02-welcome-first-prefix')
    for code in intro1[9:]:text.put(code)
    save('03-welcome-first-line')
    for code in intro2[:8]:text.put(code)
    save('04-welcome-second-prefix')
    for code in intro2[8:]:text.put(code)
    save('05-welcome-complete')
    text.clear()
    for row,code in enumerate((1,2,3,4)):
        for _ in range(32 if row<3 else 31):text.put(code)
    save('06-four-row-fill')
    text.put(4);save('07-scroll')
    text.clear();save('08-clear')
    manifest={'referenceCommit':COMMIT,
      'sources':{name:hashlib.sha256((REFERENCE/name).read_bytes()).hexdigest() for name in ('COMTXT.ASM','TXTSER.ASM','CLEAR.ASM','SWCHAR.ASM','COMDAT.ASM','MISC.ASM','ONCE.ASM','EXPAND.ASM')},
      'intro1':list(intro1),'intro2':list(intro2),'frames':records}
    (fixture/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')

if __name__=='__main__':main()
